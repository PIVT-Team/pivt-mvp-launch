import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/contexts/AuthContext";
import { useToast } from "@/hooks/use-toast";

export interface RealDeal {
  id: string;
  deal_name: string;
  deal_number: string;
  deal_value: number;
  escrow_amount: number | null;
  closing_date: string | null;
  status: string;
  created_by: string | null;
  created_at: string;
  updated_at: string;
  seed_key: string | null;
  deal_kind?: string;
  template_blueprint?: any;
}

export interface DealSummaryCounts {
  deal_id: string;
  partiesCount: number;
  docsCount: number;
  capTableCount: number;
  waterfallTiers: number;
  conditionsMet: number;
  conditionsTotal: number;
  approvalsGranted: number;
  approvalsTotal: number;
}

export interface DealTemplate {
  id: string;
  deal_name: string;
  seed_key: string | null;
}

export function useDealOperations() {
  const { user } = useAuth();
  const { toast } = useToast();

  const createDeal = async (params: {
    deal_name: string;
    deal_value: number;
    closing_date?: string | null;
    escrow_amount?: number;
    templateId?: string | null;
  }): Promise<RealDeal | null> => {
    const { data, error } = await supabase
      .from("deals")
      .insert({
        deal_name: params.deal_name,
        deal_value: params.deal_value,
        closing_date: params.closing_date || null,
        escrow_amount: params.escrow_amount || 0,
        created_by: user?.id || null,
        status: "draft",
        deal_number: "", // auto-generated by trigger
        deal_kind: "live" as any,
      })
      .select()
      .single();

    if (error) {
      toast({ title: "Error creating deal", description: error.message, variant: "destructive" });
      return null;
    }

    // Add creator as participant if authenticated
    if (user) {
      await supabase.from("deal_participants").insert({
        deal_id: data.id,
        user_id: user.id,
        party_role: "admin",
      });
    }

    // Create deal settings
    await supabase.from("deal_settings").insert({
      deal_id: data.id,
    });

    // Apply template: copy conditions + store blueprint metadata
    if (params.templateId) {
      // Copy closing conditions
      const { data: templateConditions } = await supabase
        .from("conditions")
        .select("title")
        .eq("deal_id", params.templateId);

      if (templateConditions && templateConditions.length > 0) {
        const conditionRows = templateConditions.map((c: any) => ({
          deal_id: data.id,
          title: c.title,
          status: "NOT_STARTED" as any,
        }));
        await supabase.from("conditions").insert(conditionRows as any);
      }

      // Copy blueprint metadata (role slots, compliance checks, doc categories, approvals)
      const { data: templateDeal } = await (supabase
        .from("deals")
        .select("template_blueprint") as any)
        .eq("id", params.templateId)
        .single();

      if (templateDeal?.template_blueprint) {
        await (supabase
          .from("deals")
          .update({ template_blueprint: templateDeal.template_blueprint } as any) as any)
          .eq("id", data.id);
      }
    }

    return data as RealDeal;
  };

  const fetchTemplates = async (): Promise<DealTemplate[]> => {
    const { data } = await (supabase
      .from("deals")
      .select("id, deal_name, seed_key") as any)
      .eq("deal_kind", "template")
      .order("deal_name");
    return (data as DealTemplate[]) || [];
  };

  const fetchDeals = async (): Promise<RealDeal[]> => {
    const { data } = await (supabase
      .from("deals")
      .select("*") as any)
      .in("deal_kind", ["demo", "live"])
      .order("created_at", { ascending: false });
    return (data as RealDeal[]) || [];
  };

  const fetchDeal = async (id: string): Promise<RealDeal | null> => {
    const { data } = await supabase
      .from("deals")
      .select("*")
      .eq("id", id)
      .single();
    return data as RealDeal | null;
  };

  const fetchDealSummaries = async (dealIds: string[]): Promise<Record<string, DealSummaryCounts>> => {
    if (dealIds.length === 0) return {};

    const [parties, docs, capTable, tiers, conditions, approvals] = await Promise.all([
      supabase.from("deal_participants").select("deal_id", { count: "exact", head: false }).in("deal_id", dealIds),
      supabase.from("contract_documents").select("deal_id", { count: "exact", head: false }).in("deal_id", dealIds),
      supabase.from("cap_table_entries").select("deal_id", { count: "exact", head: false }).in("deal_id", dealIds),
      supabase.from("waterfall_tiers").select("deal_id", { count: "exact", head: false }).in("deal_id", dealIds),
      supabase.from("conditions").select("deal_id, status").in("deal_id", dealIds),
      supabase.from("deal_approvals").select("deal_id, status").in("deal_id", dealIds),
    ]);

    const count = (rows: any[] | null, id: string) => (rows || []).filter((r: any) => r.deal_id === id).length;

    const result: Record<string, DealSummaryCounts> = {};
    for (const id of dealIds) {
      const condRows = (conditions.data || []).filter((r: any) => r.deal_id === id);
      const appRows = (approvals.data || []).filter((r: any) => r.deal_id === id);
      result[id] = {
        deal_id: id,
        partiesCount: count(parties.data, id),
        docsCount: count(docs.data, id),
        capTableCount: count(capTable.data, id),
        waterfallTiers: count(tiers.data, id),
        conditionsMet: condRows.filter((c: any) => c.status === 'MET').length,
        conditionsTotal: condRows.length,
        approvalsGranted: appRows.filter((a: any) => a.status === 'approved').length,
        approvalsTotal: appRows.length,
      };
    }
    return result;
  };

  return { createDeal, fetchTemplates, fetchDeals, fetchDeal, fetchDealSummaries };
}
